"""Manifest handling for .coding-standard.toml using pure Python standard library."""

from __future__ import annotations

import datetime
import hashlib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

try:
    import tomllib
except ImportError:
    tomllib = None  # type: ignore

MANIFEST_FILENAME = ".coding-standard.toml"


@dataclass
class ManagedFile:
    path: str
    profile: str
    sha256: str
    is_base: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "profile": self.profile,
            "sha256": self.sha256,
            "is_base": self.is_base,
        }


@dataclass
class Manifest:
    version: str
    repository: str = "coding-standard"
    updated_at: str = field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    )
    profiles: list[str] = field(default_factory=list)
    files: list[ManagedFile] = field(default_factory=list)

    def get_file(self, rel_path: str) -> ManagedFile | None:
        for f in self.files:
            if f.path == rel_path:
                return f
        return None

    def upsert_file(self, file_entry: ManagedFile) -> None:
        for i, existing in enumerate(self.files):
            if existing.path == file_entry.path:
                self.files[i] = file_entry
                return
        self.files.append(file_entry)

    def add_profile(self, profile: str) -> None:
        if profile not in self.profiles:
            self.profiles.append(profile)


def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 hex digest for a file."""
    h = hashlib.sha256()
    with file_path.open("rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def load_manifest(target_dir: Path) -> Manifest | None:
    """Load and parse .coding-standard.toml from target directory."""
    manifest_path = target_dir / MANIFEST_FILENAME
    if not manifest_path.exists():
        return None

    content = manifest_path.read_text(encoding="utf-8")
    if tomllib is not None:
        data = tomllib.loads(content)
    else:
        # Simple fallback parser for basic TOML if tomllib not present
        data = _parse_simple_toml(content)

    version = str(data.get("version", "unknown"))
    repository = str(data.get("repository", "coding-standard"))
    updated_at = str(data.get("updated_at", ""))
    profiles = [str(p) for p in data.get("profiles", [])]

    raw_files = data.get("files", [])
    files: list[ManagedFile] = []
    if isinstance(raw_files, list):
        for item in raw_files:
            if isinstance(item, dict):
                files.append(
                    ManagedFile(
                        path=str(item.get("path", "")),
                        profile=str(item.get("profile", "")),
                        sha256=str(item.get("sha256", "")),
                        is_base=bool(item.get("is_base", False)),
                    )
                )

    return Manifest(
        version=version,
        repository=repository,
        updated_at=updated_at,
        profiles=profiles,
        files=files,
    )


def save_manifest(target_dir: Path, manifest: Manifest) -> None:
    """Serialize and write manifest to .coding-standard.toml."""
    manifest_path = target_dir / MANIFEST_FILENAME
    profiles_str = ", ".join(f'"{p}"' for p in manifest.profiles)

    lines: list[str] = [
        "# Generated by coding-standard. DO NOT EDIT MANUALLY.",
        f'version = "{manifest.version}"',
        f'repository = "{manifest.repository}"',
        f'updated_at = "{manifest.updated_at}"',
        f"profiles = [{profiles_str}]",
        "",
    ]

    for f in manifest.files:
        lines.append("[[files]]")
        lines.append(f'path = "{f.path}"')
        lines.append(f'profile = "{f.profile}"')
        lines.append(f'sha256 = "{f.sha256}"')
        lines.append(f"is_base = {'true' if f.is_base else 'false'}")
        lines.append("")

    manifest_path.write_text("\n".join(lines), encoding="utf-8")


def _parse_simple_toml(content: str) -> dict[str, Any]:
    """Fallback parser for minimal TOML structure used by our manifest."""
    data: dict[str, Any] = {"profiles": [], "files": []}
    current_table: dict[str, Any] | None = None

    for raw_line in content.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line == "[[files]]":
            current_table = {}
            data["files"].append(current_table)
            continue
        if "=" in line:
            key, val = (part.strip() for part in line.split("=", 1))
            # Parse value
            parsed_val: Any
            if val.startswith('"') and val.endswith('"'):
                parsed_val = val[1:-1]
            elif val.lower() == "true":
                parsed_val = True
            elif val.lower() == "false":
                parsed_val = False
            elif val.startswith("[") and val.endswith("]"):
                items = [x.strip().strip('"') for x in val[1:-1].split(",") if x.strip()]
                parsed_val = items
            else:
                parsed_val = val

            if current_table is not None:
                current_table[key] = parsed_val
            else:
                data[key] = parsed_val

    return data
